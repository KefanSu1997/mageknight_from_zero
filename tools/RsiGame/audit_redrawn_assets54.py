"""Freeze untouched generated originals and compare formal battle geometry."""
import argparse,json,hashlib,shutil
from pathlib import Path
from PIL import Image
from structured_ui_ppo import state
from validate_entity_hover_reader import inside

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'AutomationOutputs/RsiGame/ui_iterations/20261024_embedded_battle_v1'
OUT=BASE/'attempt54'
def read(p):return json.loads(p.read_text(encoding='utf8'))
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--published',action='store_true');args=ap.parse_args()
    suffix='_published' if args.published else ''
    icons='icon_validation_published' if args.published else 'icon_validation_final'
    validation='validation_published' if args.published else 'validation_final'
    runtime='published_compile_receipt.json' if args.published else 'final_assets_compile_receipt.json'
    cat=OUT/'skill_icon_generation';sources={}
    for r in read(cat/'batch01_import.json')['records']:sources[r['sourceId']]=r['generated_path']
    for r in read(cat/'generator_a/selected_sources.json'):sources[r['sourceId']]=r['generatedPath']
    for r in read(cat/'generator_b/manifest.json')['items']:sources[r['sourceId']]=r['originalPath']
    assets=read(cat/'asset_manifest.json');assert len(sources)==assets['count']==70
    master=[]
    for r in assets['rows']:
        src=Path(sources[r['sourceId']]);p=Path(r['path']);assert sha(src)==sha(p)==r['sha256']
        master.append(dict(**r,generated_source=str(src),pixels_edited=False,original_generated_retained=src.exists()))
    (cat/'complete_provenance.json').write_text(json.dumps(dict(passed=True,count=70,rows=master,method='Built-in image_gen, one asset per identity, full prompt and original generated bytes retained; no card scans/crops.'),ensure_ascii=False,indent=2),encoding='utf8')
    assert read(OUT/icons/'manifest.json')['actual_source_count']==70
    rows=[]
    for label in ['three_enemies','source_taken','source_consumed']:
        a=read(OUT/'before/key_phases'/label/'capture.json');b=read(OUT/validation/'key_phases'/label/'capture.json')
        assert state(a['observation'])['audit.costNativeState']==state(b['observation'])['audit.costNativeState']
        ac={x['path']:x for x in a['observation']['controls']};bc={x['path']:x for x in b['observation']['controls']}
        assert ac.keys()==bc.keys(),label
        for p in ac:
            for k in ['x','y','width','height','clickable','interactable']:assert ac[p][k]==bc[p][k],(label,p,k)
        at={x['path']:x for x in a['evaluation']['texts']};bt={x['path']:x for x in b['evaluation']['texts']}
        for p in at.keys()&bt.keys():
            if '/Enemy_' not in p:continue
            assert at[p]['fullText']==bt[p]['fullText'] and at[p]['fontSize']==bt[p]['fontSize'],p
            text=bt[p];required={i for i,ch in enumerate(text['fullText']) if not ch.isspace()}
            assert required.issubset({g['sourceIndex'] for g in text['glyphs']}),p
            assert all(inside(g['screenRect'],dict(x=0,y=0,width=1920,height=1080),.1) for g in text['glyphs']),p
        changes=[]
        for im in b['evaluation']['rawImages']:
            if im['name']!='EnemyIllustration':continue
            assert im['uvRect']['x']==im['uvRect']['y']==0 and im['uvRect']['width']==im['uvRect']['height']==1
            if im['texture'] not in ['monster_037','monster_065','monster_068']:continue
            frame=read(ROOT/'Assets/Resources/UI/CharacterFrames/embedded_v5'/(im['texture']+'.json'))
            rect=im['screenRect'];height=frame['height']*rect['height']/im['sourceHeight']
            assert height>=300,(im['texture'],height)
            changes.append(dict(id=im['texture'],visible_alpha64_layout_height=height,full_uv=True))
        if label=='three_enemies':assert len(changes)==3
        rows.append(dict(label=label,same_native=True,unchanged_controls=len(ac),enemy_text_content_and_font_preserved=True,changed_actors=changes))
    (OUT/('geometry_audit'+suffix+'.json')).write_text(json.dumps(dict(passed=True,rows=rows,canvas=[1920,1080],scope='Three actual same-native pairs, formal hit geometries/enabledness and enemy text unchanged;3current actors >=300px alpha64 layout height and full UV. Enemy label Y intentionally tracks taller body; no global layout or human acceptance.'),ensure_ascii=False,indent=2),encoding='utf8')
    dest=OUT/('source_published' if args.published else 'source_final');files=[]
    paths=[ROOT/'Assets/Scripts/Battle'/p.name for p in (OUT/'source_before').glob('*.cs')]
    paths += [ROOT/'tools/RsiGame'/p for p in ['validate_redrawn_skill_icons54.py','audit_redrawn_assets54.py','publish_redrawn54.py','validate_skill_hover50.py','validate_embedded_party_feedback.py']]
    for p in paths:
        rel=p.relative_to(ROOT);t=dest/rel;t.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,t);files.append(dict(path=str(rel),sha256=sha(p)))
    resources=[dict(path=str(Path(r['path']).relative_to(ROOT)),sha256=r['sha256']) for r in assets['rows']]
    for r in read(OUT/'monster_portrait_import.json')['records']:
        p=Path(r['target']);resources.append(dict(path=str(p.relative_to(ROOT)),sha256=sha(p)))
        fp=ROOT/'Assets/Resources/UI/CharacterFrames/embedded_v5'/(r['id']+'.json');resources.append(dict(path=str(fp.relative_to(ROOT)),sha256=sha(fp)))
    for record in list(resources):
        meta=ROOT/(record['path']+'.meta')
        if meta.exists():resources.append(dict(path=str(meta.relative_to(ROOT)),sha256=sha(meta)))
    (OUT/('source_manifest'+suffix+'.json')).write_text(json.dumps(dict(source=files,resources=resources,runtime=read(OUT/runtime),older_versions_retained=True,whole_goal_complete=False),ensure_ascii=False,indent=2),encoding='utf8')
    print('54 source/provenance and actual geometric preservation passed')

if __name__=='__main__':main()
