"""A single real two-battle route using the original catalog picker and packaged spell definitions."""
import json
from pathlib import Path
root='Canvas/BattleTable/'
steps=[]
def click(path,label,expected=None,capture=False):
 checks={'ui.truncated':''};checks.update(expected or {})
 steps.append(dict(buttonPath=root+path,label=label,waitAfterSeconds=.3,skipScreenshot=not capture,
  after=[dict(key=k,expected=str(v),rule='原卡原图、实际费用与元素、同一玩家连续消费者') for k,v in checks.items()]))
def card(id):click('Hand/Btn_Card_'+id+'_0','选择原卡 '+id)
def play(id,choice,checks=None):
 card(id);click('Inspector/Btn_Choice_'+choice,'选择原印刷效果 '+choice);click('Inspector/Btn_Play','实际支付并出牌',checks)
def target(i):click(f'Enemy_{i}/Btn_Target','选择实际敌人 '+str(i))
def next():click('Inspector/Btn_Next','正式推进战斗阶段')
picker='CampShade/DeedPicker/'
(click('Btn_Menu', '打开战斗菜单'), click('Btn_Camp','打开构筑',{'catalog.deeds':121,'catalog.spells':24}))
click('CampShade/Camp/Btn_Loadout','复用红蓝各2的合法资源起点')
click('CampShade/Picker/Btn_NextPage','下一构筑页')
click('CampShade/Picker/Btn_Select_20','选择灵魂收割者原构筑资源')
click('CampShade/Camp/Btn_ChooseCards','打开原卡分类点选')
click(picker+'Btn_ClearDeeds','清空自定起点手牌')
click(picker+'Btn_ChooseDeed_basic_card_000','选择实际行进原卡')
click(picker+'Btn_DeedNext','基础行动第二页')
click(picker+'Btn_ChooseDeed_basic_card_021','选择实际狂怒原卡')
click(picker+'Btn_DeedNext','基础行动第三页')
click(picker+'Btn_ChooseDeed_basic_card_024','选择实际灵活战斗原卡')
click(picker+'Btn_ChooseDeed_basic_card_027','选择实际本能原卡')
click(picker+'Btn_DeedKind_2','切换原法术目录',capture=True)
click(picker+'Btn_ChooseDeed_magic_009','选择原火焰魔球')
click(picker+'Btn_DeedNext','原法术第二页')
click(picker+'Btn_ChooseDeed_magic_015','选择原风雪交加')
click(picker+'Btn_ChooseDeed_magic_017','选择原魔力箭矢')
click(picker+'Btn_DoneDeeds','确认7张实际原卡构筑')
click('CampShade/Camp/Btn_Journey','由原卡构筑开始连续旅程',{'hand':7})
click('Tactic_day_1/Btn_Tactic_day_1','取得原捷足先登')
click('Btn_BeginTurn','正式开始第一回合')
click('Btn_JourneyEncounter_0','面对真实原哨卫',{'red':2,'blue':2,'hand':7})
card('magic_009');click('Inspector/Btn_Choice_strong','查看原下半火焰风暴')
click('Inspector/Btn_Play','白昼拒绝下半，费用与原牌不变',{'red':2,'hand':7,'played':0,'rejections':1})
click('Inspector/Btn_Choice_base','改选原上半火焰魔球')
click('Inspector/Btn_Play','支付原红费获得火焰远程5',{'red':1,'ranged':5,'hand':6},True)
target(0);click('Inspector/Btn_Resolve','原火焰远程实际击败护甲3',{'kills':1,'fame':2})
next();next();next();next()
click('Inspector/Btn_EndTurn','真实结束回合，原法术进弃牌',{'journey.completedTurns':1,'hand':6,'played':0})
click('Btn_BeginTurn','同一玩家开始第二回合')
click('Btn_JourneyEncounter_2','进入两个新原敌标记',{'red':1,'blue':2})
play('magic_015','base',{'blue':1,'ranged':5});target(0);click('Inspector/Btn_Resolve','寒冰远程击败其中一敌',{'kills':1,'fame':4})
next();play('basic_card_024','strong_fire_block',{'red':0,'block':3})
card('basic_card_000');click('Inspector/Btn_Sideways','原行进横置补普通格挡1',{'block':4})
target(1);click('Inspector/Btn_Resolve','火焰3与普通1实际格挡攻击4',{'block':0})
next();click('Inspector/Btn_Next','已挡原攻击，不产生伤牌',{'wounds':0})
card('magic_017')
click('Inspector/Btn_MoreChoices','实际切换原魔力箭矢其他选项')
click('Inspector/Btn_MoreChoices','返回原魔力箭矢第一页')
click('Inspector/Btn_Choice_base_Blue','选择额外蓝色费用的原寒冰攻击')
click('Inspector/Btn_Play','蓝加蓝整笔费用不足，原牌与资源保持',{'blue':1,'played':3,'rejections':2,'melee':0},True)
play('basic_card_027','attack',{'melee':2});play('basic_card_021','attack',{'melee':4})
target(1);click('Inspector/Btn_Resolve','两张原卡合并攻击4，实际击败护甲3',{'fame':6,'kills':2})
next();click('Inspector/Btn_EndTurn','正式结束第二回合，保留未用原魔力箭矢',{'journey.completedTurns':2,'journey.completedBattles':2,'hand':1,'hand.ids':'magic_017','red':0,'blue':1,'played':0},True)
config=dict(scenePath='Assets/Scenes/Part1/Part1_PveBattle.unity',captureInitialView=False,initialDelaySeconds=2,
 defaultWaitAfterSeconds=.3,maxRunSeconds=240,useRunSubfolder=False,steps=steps)
Path('AutomationConfigs/pve_battle.json').write_text(json.dumps(config,ensure_ascii=False,indent=2),encoding='utf-8')
print(len(steps),'steps',sum(len(s['after']) for s in steps),'checks')
