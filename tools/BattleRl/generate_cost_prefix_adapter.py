def method(path,needle):
    source=path.read_text(encoding='utf-8-sig');start=source.index(needle)
    # Mask literals/comments for brace matching, preserving offsets.
    masked=re.sub(r'//[^\n]*|/\*[\s\S]*?\*/|@"(?:""|[^"])*"|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',lambda m:' '*len(m[0]),source)
    semi=masked.find(';',start);brace=masked.find('{',start)
    arrow=masked.find('=>',start)
    if arrow>=0 and arrow<brace:return source[start:semi+1]
    if semi>=0 and (brace<0 or semi<brace):return source[start:semi+1]
    depth=0
    for end in range(brace,len(masked)):
        if masked[end]=='{':depth+=1
        elif masked[end]=='}':
            depth-=1
            if depth==0:
                end+=1
                if source[end:end+1]==';':end+=1
                return source[start:end]
    raise ValueError(needle)


