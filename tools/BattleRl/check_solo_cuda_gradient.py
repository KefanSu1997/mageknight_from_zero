"""Trusted, SHA-bound local public fixture transfer; CUDA gradient test, no PPO."""
import hashlib
import json
from pathlib import Path
import time
import torch
from solo_public_schema import PublicSchema
from solo_structured_policy import SoloStructuredPolicy


root=Path(__file__).resolve().parent
manifest=json.loads((root/'manifest.json').read_text())
for name,expected in manifest['files'].items():
    if hashlib.sha256((root/name).read_bytes()).hexdigest()!=expected:
        raise ValueError('Transferred fixture/source SHA differs: '+name)
assert torch.cuda.is_available()
torch.set_num_threads(1)
# This file was generated by our local gate and has just been SHA-verified.
fixture=torch.load(root/'fixture.pt',map_location='cpu',weights_only=False)
schema=PublicSchema(root/'public_dto_schema.json')
model=SoloStructuredPolicy(schema,fixture['catalog_signature']).cuda()
model.load_state_dict(fixture['weights']);model.train()
torch.cuda.reset_peak_memory_stats();torch.cuda.synchronize();start=time.perf_counter()
values,logs,entropy,_=model.evaluate_sequence(fixture['prepared'],fixture['actions'])
torch.testing.assert_close(values,fixture['values'].cuda(),rtol=1e-4,atol=1e-5)
torch.testing.assert_close(logs,fixture['logs'].cuda(),rtol=1e-4,atol=1e-5)
# A probe objective exercises both heads. It is not an RL return or a PPO update.
loss=values.square().mean()-logs.mean()
loss.backward();torch.cuda.synchronize()
gradients={name:dict(finite=bool(torch.isfinite(p.grad).all()),norm=float(p.grad.norm()))
           for name,p in model.named_parameters() if p.grad is not None}
assert gradients and all(x['finite'] for x in gradients.values())
for prefix in ('structured.','policy.actor_lstm.','policy.critic_lstm.','policy.entity_text.'):
    assert any(name.startswith(prefix) and row['norm']>0 for name,row in gradients.items()),prefix
result=dict(passed=True,device=torch.cuda.get_device_name(),decisions=len(fixture['actions']),
            seconds=time.perf_counter()-start,peak_allocated_bytes=torch.cuda.max_memory_allocated(),
            max_value_difference=float((values.detach().cpu()-fixture['values']).abs().max()),
            max_logp_difference=float((logs.detach().cpu()-fixture['logs']).abs().max()),
            gradients=gradients,optimizer_steps=0,training_started=False,
            scope='CPU/CUDA inference agreement and finite recurrent gradients on native partial trajectory; no PPO or learning claim')
(root/'result.json').write_text(json.dumps(result,indent=2))
print(json.dumps({k:v for k,v in result.items() if k!='gradients'}))
